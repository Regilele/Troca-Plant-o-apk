import { monthBounds, normalizeMonthlyReport } from './domain.js';

const MONTHS_PT = [
  'Janeiro', 'Fevereiro', 'Março', 'Abril', 'Maio', 'Junho',
  'Julho', 'Agosto', 'Setembro', 'Outubro', 'Novembro', 'Dezembro',
];

export function monthLabel(month, lang = 'pt') {
  const [y, m] = month.split('-').map(Number);
  const name = MONTHS_PT[m - 1];
  if (lang === 'en') {
    return new Date(Date.UTC(y, m - 1, 1)).toLocaleDateString('en-US', { month: 'long', year: 'numeric' });
  }
  return `${name} de ${y}`;
}

export function roleLabel(role) {
  const labels = { admin: 'Administrador', member: 'Plantonista', guest: 'Convidado' };
  return labels[role] || role;
}

function formatBR(date) {
  if (!date) return '—';
  const [y, m, d] = date.split('-');
  return `${d}/${m}/${y}`;
}

/** Corpo do relatório mensal (mesmo conteúdo do e-mail/PDF do app original + pagamento separado). */
export function monthlyReportText({ month, shifts, offDays, collaborators }, lang = 'pt') {
  const report = normalizeMonthlyReport({ month, shifts, offDays, collaborators });
  const [year, m] = month.split('-');
  const monthName = lang === 'en' ? monthLabel(month, 'en') : monthLabel(month, 'pt');
  const lines = [];
  lines.push('### RG&SA PLANTÃO ###');
  lines.push('');
  lines.push(lang === 'en' ? `Monthly Shifts Report - ${monthName}` : `Relatório Mensal de Escalas - ${monthName}`);
  lines.push('');
  lines.push(lang === 'en' ? '--- Shifts ---' : '--- Plantões ---');
  for (const row of report.shifts) {
    const swap = row.swapForDate ? ` | Troca: ${formatBR(row.swapForDate)}` : '';
    const payment = row.paymentDate ? ` | Pagamento: ${formatBR(row.paymentDate)}` : ' | Pagamento: a definir';
    const home = row.atHome === '-x-' ? (lang === 'en' ? 'On duty' : 'Ocupado (-x-)') : row.atHome ? (lang === 'en' ? `At home (${row.atHome})` : `Em Casa (${row.atHome})`) : '';
    lines.push(
      `- Data: ${formatBR(row.date)} | Profissional: ${row.onShift} | Período: ${row.period}${swap}${payment}${home ? ` | Casa: ${home}` : ''}`,
    );
  }
  if (report.shifts.length === 0) lines.push(lang === 'en' ? 'No shifts scheduled in this period.' : 'Nenhum plantão agendado para o período.');
  lines.push('');
  lines.push(lang === 'en' ? '--- Off-days ---' : '--- Folgas ---');
  for (const row of report.offDays) {
    lines.push(`- Data: ${formatBR(row.date)} | Profissional: ${row.name} | Tipo: ${row.type}`);
  }
  if (report.offDays.length === 0) lines.push(lang === 'en' ? 'No off-days in this period.' : 'Nenhuma folga cadastrada no período.');
  lines.push('');
  lines.push(lang === 'en' ? 'Totals:' : 'Totais:');
  lines.push(
    lang === 'en'
      ? `Shifts: ${report.stats.shifts} | Swaps: ${report.stats.swaps} | Off-days: ${report.stats.offDays} | Payments pending: ${report.stats.pendingPayments}`
      : `Plantões: ${report.stats.shifts} | Trocas: ${report.stats.swaps} | Folgas: ${report.stats.offDays} | Pagamentos a definir: ${report.stats.pendingPayments}`,
  );
  lines.push('');
  lines.push(lang === 'en' ? 'Support: +55 (21) 98049-8068' : 'Suporte e Atendimento: +55 (21) 98049-8068');
  lines.push('');
  lines.push(lang === 'en' ? 'Generated by RG&SA PLANTÃO (web/PWA).' : 'Gerado pelo RG&SA PLANTÃO (web/PWA).');
  return { text: lines.join('\n'), report, monthName, year, monthNumber: m };
}

export function reportMeta(month) {
  return { ...monthBounds(month), label: monthLabel(month) };
}
